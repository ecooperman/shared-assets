// Exposed (not run-once-and-forgotten) because pages often build a lot of
// their DOM dynamically after load - anything that creates a `data-icon`
// element after the initial pass needs to call this again on it, or the
// span stays empty.
function applyIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const svg = ICONS[el.dataset.icon];
    if (svg) el.innerHTML = svg;
  });
}

applyIcons();
